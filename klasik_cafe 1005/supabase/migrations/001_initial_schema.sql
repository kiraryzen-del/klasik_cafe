create extension if not exists pgcrypto with schema extensions;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  first_name text not null default '',
  last_name text not null default '',
  username text not null unique,
  phone text not null default '',
  role text not null default 'customer' check (role in ('customer', 'admin', 'barista')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.menu_categories (
  id uuid primary key default extensions.gen_random_uuid(),
  slug text not null unique,
  name text not null,
  parent_id uuid references public.menu_categories (id) on delete restrict,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.menu_items (
  id uuid primary key default extensions.gen_random_uuid(),
  source_key text unique,
  category_id uuid not null references public.menu_categories (id) on delete restrict,
  sort_order integer not null default 0,
  name text not null,
  description text not null default '',
  price numeric(10, 2) not null check (price >= 0),
  image_path text not null default '',
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.menu_addons (
  id uuid primary key default extensions.gen_random_uuid(),
  slug text not null unique,
  name text not null,
  price numeric(10, 2) not null check (price >= 0),
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default extensions.gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid not null references public.profiles (id) on delete restrict,
  status text not null default 'Pending'
    check (status in ('Pending', 'Accepted', 'Preparing', 'Ready', 'Completed', 'Cancelled')),
  subtotal numeric(10, 2) not null check (subtotal >= 0),
  total numeric(10, 2) not null check (total >= 0),
  special_requests text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default extensions.gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete cascade,
  menu_item_id uuid references public.menu_items (id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity between 1 and 99),
  unit_price numeric(10, 2) not null check (unit_price >= 0),
  customizations jsonb not null default '{}'::jsonb,
  selected_addons jsonb not null default '[]'::jsonb
    check (jsonb_typeof(selected_addons) = 'array'),
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id uuid primary key default extensions.gen_random_uuid(),
  customer_id uuid not null references public.profiles (id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text not null check (length(trim(comment)) > 0),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.suggestions (
  id uuid primary key default extensions.gen_random_uuid(),
  customer_id uuid not null references public.profiles (id) on delete cascade,
  subject text not null check (length(trim(subject)) > 0),
  suggestion text not null check (length(trim(suggestion)) > 0),
  status text not null default 'New' check (status in ('New', 'Reviewing', 'Resolved')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cafe_info (
  singleton boolean primary key default true check (singleton),
  name text not null,
  address text not null default '',
  opening_hours text not null default '',
  phone text not null default '',
  facebook text not null default '',
  instagram text not null default '',
  tiktok text not null default '',
  description text not null default '',
  updated_at timestamptz not null default now()
);

