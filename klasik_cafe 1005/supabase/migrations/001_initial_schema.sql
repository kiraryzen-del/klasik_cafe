create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'profiles', 'menu_categories', 'menu_items', 'menu_addons',
    'orders', 'reviews', 'suggestions', 'cafe_info'
  ]
  loop
    execute format('drop trigger if exists set_updated_at on public.%I', table_name);
    execute format(
      'create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()',
      table_name
    );
  end loop;
end;
$$;

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.role
  from public.profiles as p
  where p.id = (select auth.uid())
$$;

create or replace function public.is_staff(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.current_user_role() = any (allowed_roles), false)
$$;

create or replace function public.create_customer_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, first_name, last_name, username, phone, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'first_name', ''),
    coalesce(new.raw_user_meta_data ->> 'last_name', ''),
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'username'), ''), split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'phone', ''),
    'customer'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists auth_user_profile_created on auth.users;
create trigger auth_user_profile_created
after insert on auth.users
for each row execute function public.create_customer_profile();

create or replace function public.place_order(p_items jsonb, p_special_requests text default '')
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id uuid;
  v_item jsonb;
  v_item_id uuid;
  v_quantity integer;
  v_customizations jsonb;
  v_addon_ids uuid[];
  v_product_name text;
  v_unit_price numeric(10, 2);
  v_addons jsonb;
  v_subtotal numeric(10, 2) := 0;
  v_item_count integer;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication is required to place an order';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'Order items must be a JSON array';
  end if;

  v_item_count := jsonb_array_length(p_items);
  if v_item_count < 1 or v_item_count > 50 then
    raise exception 'An order must contain between 1 and 50 line items';
  end if;

  insert into public.orders (customer_id, subtotal, total, special_requests)
  values ((select auth.uid()), 0, 0, coalesce(p_special_requests, ''))
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce(v_item ->> 'quantity', '') !~ '^[0-9]+$' then
      raise exception 'Each quantity must be a whole number';
    end if;

    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity < 1 or v_quantity > 99 then
      raise exception 'Each quantity must be between 1 and 99';
    end if;

    v_item_id := (v_item ->> 'menu_item_id')::uuid;
    v_customizations := coalesce(v_item -> 'customizations', '{}'::jsonb);
    if jsonb_typeof(v_customizations) <> 'object' then
      raise exception 'Customizations must be a JSON object';
    end if;

    select m.name, m.price
      into v_product_name, v_unit_price
      from public.menu_items as m
      where m.id = v_item_id and m.is_available;
    if not found then
      raise exception 'A menu item is unavailable or does not exist';
    end if;

    if jsonb_typeof(coalesce(v_item -> 'addon_ids', '[]'::jsonb)) <> 'array' then
      raise exception 'Add-on IDs must be a JSON array';
    end if;

    select coalesce(array_agg(value::uuid), '{}'::uuid[])
      into v_addon_ids
      from jsonb_array_elements_text(coalesce(v_item -> 'addon_ids', '[]'::jsonb));

    if cardinality(v_addon_ids) <> (
      select count(distinct addon_value)
      from unnest(v_addon_ids) as addon_values(addon_value)
    ) then
      raise exception 'An add-on cannot be selected more than once';
    end if;

    select v_unit_price + coalesce(sum(a.price), 0),
           coalesce(jsonb_agg(jsonb_build_object('id', a.id, 'name', a.name, 'price', a.price)), '[]'::jsonb)
      into v_unit_price, v_addons
      from public.menu_addons as a
      where a.id = any(v_addon_ids) and a.is_available;

    if cardinality(v_addon_ids) <> jsonb_array_length(coalesce(v_item -> 'addon_ids', '[]'::jsonb)) then
      raise exception 'An add-on is unavailable or does not exist';
    end if;

    insert into public.order_items (
      order_id, menu_item_id, product_name, quantity, unit_price, customizations, selected_addons
    )
    values (
      v_order_id, v_item_id, v_product_name, v_quantity, v_unit_price, v_customizations, v_addons
    );
    v_subtotal := v_subtotal + v_unit_price * v_quantity;
  end loop;

  update public.orders
    set subtotal = v_subtotal, total = v_subtotal
    where id = v_order_id;

  return v_order_id;
end;
$$;

create or replace function public.update_order_status(p_order_id uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_staff(array['admin', 'barista']) then
    raise exception 'Only authorized staff can update order status';
  end if;
  if p_status not in ('Pending', 'Accepted', 'Preparing', 'Ready', 'Completed', 'Cancelled') then
    raise exception 'Invalid order status';
  end if;

  update public.orders
    set status = p_status
    where id = p_order_id;
  if not found then
    raise exception 'Order not found';
  end if;
end;
$$;

